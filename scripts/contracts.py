"""
FOLO's contracts (RB-02): bundles the JSON Schemas, generates the Python,
Rust and TypeScript types from them, validates OpenAPI and AsyncAPI, and
checks that everything generated is up to date.

    uv run python scripts/contracts.py bundle      # specs/generated/folo.schema.json
    uv run python scripts/contracts.py generate    # bundle + all generated code
    uv run python scripts/contracts.py check       # validate, and fail on drift

Generated files are committed; CI runs `check`.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Callable
from pathlib import Path
from typing import Any, cast

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_DIR = ROOT / 'specs' / 'schema'
BUNDLE = ROOT / 'specs' / 'generated' / 'folo.schema.json'
OPENAPI = ROOT / 'specs' / 'openapi.yaml'
ASYNCAPI = ROOT / 'specs' / 'asyncapi.yaml'
PY_MODELS = ROOT / 'app' / 'contracts' / 'models.py'
RS_MODELS = ROOT / 'crates' / 'folo-protocol' / 'src' / 'generated.rs'
TS_MODELS = ROOT / 'ui' / 'src' / 'lib' / 'api' / 'schema.ts'
PY_UNICODE = ROOT / 'crates' / 'folo-protocol' / 'src' / 'v1' / 'pyunicode.rs'
UI_DIR = ROOT / 'ui'

Json = Any


def _obj(node: Json) -> dict[str, Json] | None:
    """A JSON value as an object, or None."""
    return cast('dict[str, Json]', node) if isinstance(node, dict) else None


def _arr(node: Json) -> list[Json] | None:
    """A JSON value as a list, or None."""
    return cast('list[Json]', node) if isinstance(node, list) else None


def _schema_files() -> list[Path]:
    return sorted(SCHEMA_DIR.glob('*.json'))


def _load(path: Path) -> dict[str, Json]:
    return json.loads(path.read_text(encoding='utf-8'))


def _is_schema_root(schema: dict[str, Json]) -> bool:
    """Whether a file's root is a schema of its own (a document), not only a $defs container."""
    return any(key in schema for key in ('type', 'properties', 'oneOf', 'anyOf'))


def bundle() -> dict[str, Json]:
    """
    One schema with every definition in a single $defs namespace: the
    documents under their title, and every file's $defs. References between
    files become local ones.
    """
    titles: dict[str, str] = {}
    files = _schema_files()
    for path in files:
        titles[path.name] = _load(path)['title']
    defs: dict[str, Json] = {}

    def add(name: str, schema: Json, origin: str) -> None:
        if name in defs:
            raise SystemExit(f'{origin}: definition {name} is already defined elsewhere')
        defs[name] = schema

    def rewrite_ref(ref: str, current: str) -> str:
        target, _, pointer = ref.partition('#')
        file_name = target or current
        if file_name not in titles:
            raise SystemExit(f'{current}: reference to an unknown file: {ref}')
        if pointer in ('', '/'):
            return f'#/$defs/{titles[file_name]}'
        if not pointer.startswith('/$defs/'):
            raise SystemExit(f'{current}: only #/$defs/... references are supported: {ref}')
        return f'#{pointer}'

    def rewrite(node: Json, current: str) -> Json:
        if (obj := _obj(node)) is not None:
            out: dict[str, Json] = {}
            for key, value in obj.items():
                by_effect = _obj(value) if key == 'x-folo-params-by-effect' else None
                if key == '$ref' and isinstance(value, str):
                    out[key] = rewrite_ref(value, current)
                elif by_effect is not None:
                    out[key] = {
                        effect: rewrite_ref(str(ref), current) for effect, ref in by_effect.items()
                    }
                else:
                    out[key] = rewrite(value, current)
            return out
        if (items := _arr(node)) is not None:
            return [rewrite(item, current) for item in items]
        return node

    for path in files:
        schema = _load(path)
        if _is_schema_root(schema):
            root = {k: v for k, v in schema.items() if k not in ('$schema', '$defs')}
            add(schema['title'], rewrite(root, path.name), path.name)
        for name, definition in schema.get('$defs', {}).items():
            add(name, rewrite(definition, path.name), path.name)
    _check_refs(defs)
    _materialize_defaults(defs)
    return {
        '$schema': 'https://json-schema.org/draft/2020-12/schema',
        '$comment': 'Generated by scripts/contracts.py from specs/schema/*.json. Do not edit.',
        '$defs': dict(sorted(defs.items())),
    }


def _resolve(defs: dict[str, Json], schema: Json) -> dict[str, Json]:
    obj = _obj(schema) or {}
    while '$ref' in obj:
        obj = _obj(defs[str(obj['$ref']).removeprefix('#/$defs/')]) or {}
    return obj


def _branch(defs: dict[str, Json], union: dict[str, Json], value: Json) -> dict[str, Json] | None:
    """The oneOf branch whose kind constant matches value['kind']."""
    obj = _obj(value)
    if obj is None:
        return None
    for option in _arr(union['oneOf']) or []:
        branch = _resolve(defs, option)
        if branch.get('properties', {}).get('kind', {}).get('const') == obj.get('kind'):
            return branch
    return None


def materialize(defs: dict[str, Json], schema: Json, value: Json) -> Json:
    """
    A default written as a partial object ({} or {"kind": "line"}) made
    complete from the properties' own defaults, which is what the clamping
    rules make of it. Generators then see every field's real default.
    """
    resolved = _resolve(defs, schema)
    if 'oneOf' in resolved:
        branch = _branch(defs, resolved, value)
        return materialize(defs, branch, value) if branch is not None else value
    properties = _obj(resolved.get('properties'))
    if (obj := _obj(value)) is not None and properties is not None:
        out = dict(obj)
        for name, prop in properties.items():
            prop_schema = _obj(prop) or {}
            if name in out:
                out[name] = materialize(defs, prop_schema, out[name])
            elif 'default' in prop_schema:
                out[name] = materialize(defs, prop_schema, prop_schema['default'])
            elif 'const' in prop_schema:
                out[name] = prop_schema['const']
        return out
    if (items := _arr(value)) is not None and 'items' in resolved:
        return [materialize(defs, resolved['items'], item) for item in items]
    return value


def _materialize_defaults(defs: dict[str, Json]) -> None:
    def walk(node: Json) -> None:
        if (obj := _obj(node)) is not None:
            default = obj.get('default')
            if _obj(default) is not None or _arr(default) is not None:
                target = {k: v for k, v in obj.items() if k != 'default'}
                obj['default'] = materialize(defs, target, default)
            for value in obj.values():
                walk(value)
        elif (items := _arr(node)) is not None:
            for item in items:
                walk(item)

    for definition in defs.values():
        walk(definition)


def _check_refs(defs: dict[str, Json]) -> None:
    """Every local reference in the bundle names a definition."""

    def walk(node: Json, where: str) -> None:
        if (obj := _obj(node)) is not None:
            ref = obj.get('$ref')
            if isinstance(ref, str) and ref.removeprefix('#/$defs/') not in defs:
                raise SystemExit(f'{where}: unresolved reference {ref}')
            for value in obj.values():
                walk(value, where)
        elif (items := _arr(node)) is not None:
            for item in items:
                walk(item, where)

    for name, definition in defs.items():
        walk(definition, name)


def _bundle_text() -> str:
    return json.dumps(bundle(), indent=1, ensure_ascii=False) + '\n'


def write_bundle(path: Path = BUNDLE) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_bundle_text(), encoding='utf-8')


# ---------------------------------------------------------------- generators

PY_HEADER = (
    '# Generated by scripts/contracts.py from specs/generated/folo.schema.json. Do not edit.\n'
    # Object defaults are written as dicts, which pydantic validates into the
    # models (validate_default=True); pyright can't see that conversion
    '# pyright: reportAssignmentType=false'
)


def _run(cmd: list[str], cwd: Path = ROOT) -> None:
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, encoding='utf-8')
    if result.returncode:
        raise SystemExit(f'{" ".join(cmd)} failed:\n{result.stdout}\n{result.stderr}')


def _tool(name: str) -> str:
    found = shutil.which(name)
    if found is None:
        raise SystemExit(f'{name} is needed (see CONTRIBUTING.md)')
    return found


def generate_python(bundle_path: Path, out: Path) -> None:
    """
    pydantic v2 models (datamodel-code-generator). It writes into a temporary
    folder first: inside the repository it would pick up pyproject.toml's
    settings, and a check run would format differently.
    """
    with tempfile.TemporaryDirectory() as tmp:
        staged = Path(tmp) / out.name
        _generate_python(bundle_path, staged)
        shutil.copyfile(staged, out)


def _generate_python(bundle_path: Path, out: Path) -> None:
    _run(
        [
            sys.executable,
            '-m',
            'datamodel_code_generator',
            '--input',
            str(bundle_path),
            '--input-file-type',
            'jsonschema',
            '--output',
            str(out),
            '--output-model-type',
            'pydantic_v2.BaseModel',
            '--target-python-version',
            '3.13',
            '--formatters',
            'builtin',
            '--disable-timestamp',
            '--custom-file-header',
            PY_HEADER,
            '--class-name',
            'FoloSchema',
            '--enum-field-as-literal',
            'all',
            '--use-annotated',
            '--field-constraints',
            '--use-default',
            '--strict-nullable',
            '--use-schema-description',
            '--use-title-as-name',
            '--use-standard-collections',
            '--use-union-operator',
            '--collapse-root-models',
        ]
    )
    # The same file on every platform
    out.write_text(out.read_text(encoding='utf-8').replace('\r\n', '\n'), encoding='utf-8')


def generate_rust(bundle_path: Path, out: Path) -> None:
    """serde types through typify (crates/xtask)."""
    _run(
        [
            _tool('cargo'),
            'run',
            '--quiet',
            '--locked',
            '-p',
            'xtask',
            '--',
            'protocol',
            str(bundle_path),
            str(out),
        ]
    )


def generate_typescript(out: Path) -> None:
    """Client API types from OpenAPI (openapi-typescript in ui/)."""
    binary = (
        UI_DIR
        / 'node_modules'
        / '.bin'
        / ('openapi-typescript.cmd' if os.name == 'nt' else 'openapi-typescript')
    )
    if not binary.exists():
        raise SystemExit('Run `npm ci` in ui/ first')
    _run([str(binary), str(OPENAPI), '--output', str(out)], cwd=UI_DIR)


def generate_pyunicode(out: Path) -> None:
    """Python's Unicode facts for the Rust port of the version-1 rules (scripts/pyunicode.py)."""
    _run([sys.executable, str(ROOT / 'scripts' / 'pyunicode.py'), str(out)])


def generate() -> None:
    write_bundle()
    print(f'wrote {BUNDLE.relative_to(ROOT)}')
    PY_MODELS.parent.mkdir(parents=True, exist_ok=True)
    generate_python(BUNDLE, PY_MODELS)
    print(f'wrote {PY_MODELS.relative_to(ROOT)}')
    generate_rust(BUNDLE, RS_MODELS)
    print(f'wrote {RS_MODELS.relative_to(ROOT)}')
    TS_MODELS.parent.mkdir(parents=True, exist_ok=True)
    generate_typescript(TS_MODELS)
    print(f'wrote {TS_MODELS.relative_to(ROOT)}')
    generate_pyunicode(PY_UNICODE)
    print(f'wrote {PY_UNICODE.relative_to(ROOT)}')


# ---------------------------------------------------------------- checks


def check_schemas() -> list[str]:
    """Every schema file is valid 2020-12, and every default satisfies its own schema."""
    from jsonschema import Draft202012Validator
    from jsonschema.exceptions import SchemaError

    problems: list[str] = []
    for path in _schema_files():
        try:
            Draft202012Validator.check_schema(_load(path))
        except SchemaError as exc:
            problems.append(f'{path.name}: {exc.message}')
    defs: dict[str, Json] = bundle()['$defs']

    def check_default(node: Json, where: str) -> None:
        if (obj := _obj(node)) is not None:
            if 'default' in obj:
                schema: dict[str, Json] = {k: v for k, v in obj.items() if k != 'default'}
                validator = Draft202012Validator({**schema, '$defs': defs})
                errors = validator.iter_errors(obj['default'])  # pyright: ignore[reportUnknownMemberType]
                message = next((e.message for e in errors), None)
                if message is not None:
                    problems.append(f'{where}: default {obj["default"]!r} is invalid: {message}')
            for key, value in obj.items():
                check_default(value, f'{where}.{key}')
        elif (items := _arr(node)) is not None:
            for i, item in enumerate(items):
                check_default(item, f'{where}[{i}]')

    for name, definition in defs.items():
        check_default(definition, name)
    return problems


def check_openapi() -> list[str]:
    from openapi_spec_validator import validate
    from openapi_spec_validator.readers import read_from_filename

    spec, _ = read_from_filename(str(OPENAPI))
    try:
        validate(spec, base_uri=OPENAPI.as_uri())
    except Exception as exc:  # the validator raises several kinds
        return [f'{OPENAPI.name}: {exc}']
    return []


def check_asyncapi() -> list[str]:
    node = shutil.which('node')
    script = UI_DIR / 'scripts' / 'check-asyncapi.mjs'
    if node is None or not (UI_DIR / 'node_modules' / '@asyncapi').exists():
        return ['AsyncAPI not checked: run `npm ci` in ui/ (needs Node.js)']
    result = subprocess.run(
        [node, str(script), str(ASYNCAPI)],
        cwd=UI_DIR,
        capture_output=True,
        text=True,
        encoding='utf-8',
    )
    if result.returncode:
        return [f'{ASYNCAPI.name}: {result.stdout.strip()} {result.stderr.strip()}']
    return []


def _diff(name: str, committed: Path, fresh: Path) -> list[str]:
    old = committed.read_text(encoding='utf-8').splitlines() if committed.exists() else []
    new = fresh.read_text(encoding='utf-8').splitlines()
    if old == new:
        return []
    lines = list(
        difflib.unified_diff(
            old, new, str(committed.relative_to(ROOT)), 'generated', lineterm='', n=1
        )
    )
    preview = '\n'.join(lines[:40])
    return [f'{name} is out of date: run `uv run python scripts/contracts.py generate`\n{preview}']


def check_drift() -> list[str]:
    problems: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        fresh_bundle = work / 'folo.schema.json'
        write_bundle(fresh_bundle)
        problems += _diff('The schema bundle', BUNDLE, fresh_bundle)
        steps: list[tuple[str, Path, Callable[[Path], None]]] = [
            ('The Python models', PY_MODELS, lambda out: generate_python(fresh_bundle, out)),
            ('The Rust types', RS_MODELS, lambda out: generate_rust(fresh_bundle, out)),
            ('The TypeScript types', TS_MODELS, generate_typescript),
            ("Python's Unicode tables", PY_UNICODE, generate_pyunicode),
        ]
        for name, committed, make in steps:
            out = work / committed.name
            make(out)
            problems += _diff(name, committed, out)
    return problems


def check() -> None:
    problems = check_schemas() + check_openapi() + check_asyncapi() + check_drift()
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        raise SystemExit(f'{len(problems)} contract problem(s)')
    print('contracts: schemas, OpenAPI and AsyncAPI valid; generated code up to date')


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument('command', choices=['bundle', 'generate', 'check'])
    args = parser.parse_args()
    if args.command == 'bundle':
        write_bundle()
        print(f'wrote {BUNDLE.relative_to(ROOT)}')
    elif args.command == 'generate':
        generate()
    else:
        check()


if __name__ == '__main__':
    main()
