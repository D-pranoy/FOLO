"""
Writes crates/folo-protocol/src/v1/pyunicode.rs: the Unicode facts behind
Python's str methods (isprintable, isspace, lower, the decimal digits float()
reads), taken from this Python's own behaviour, so the Rust port of the
version-1 config rules matches Python exactly (RB-02 step 4).

    uv run python scripts/pyunicode.py [OUT]

scripts/contracts.py runs it as part of `generate` and `check`.
"""

from __future__ import annotations

import sys
import unicodedata
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'crates' / 'folo-protocol' / 'src' / 'v1' / 'pyunicode.rs'
SIGMA = 'Σ'


def _ranges(test: Callable[[str], bool]) -> list[tuple[int, int]]:
    """Inclusive ranges of the code points where test is true."""
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(0x110000):
        hit = test(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def _cased(c: str) -> bool:
    return c.islower() or c.isupper() or c.istitle()


def _case_ignorable(c: str) -> bool:
    # How str.lower() treats a final capital sigma: it skips case-ignorable
    # characters before it and needs a cased one. 'A' + c + 'Σ' ends in ς when
    # c is case-ignorable or cased; '1' + c + 'Σ' when c is cased and not ignorable.
    if c == SIGMA:
        return False
    after_letter = ('A' + c + SIGMA).lower().endswith('ς')
    after_digit = ('1' + c + SIGMA).lower().endswith('ς')
    return after_letter and not after_digit


def _rust_ranges(name: str, ranges: list[tuple[int, int]], doc: str) -> str:
    rows = ',\n'.join(f'    (0x{a:04X}, 0x{b:04X})' for a, b in ranges)
    return f'/// {doc}\npub const {name}: &[(u32, u32)] = &[\n{rows},\n];\n'


def generate() -> str:
    lower: list[tuple[int, str]] = []
    for cp in range(0x110000):
        c = chr(cp)
        if c != SIGMA and c.lower() != c:
            lower.append((cp, c.lower()))
    decimals: list[tuple[int, int]] = []
    for cp in range(0x110000):
        value = unicodedata.decimal(chr(cp), None)
        if value is not None:
            decimals.append((cp, value))
    lower_rows = ',\n'.join(
        '    (0x{:04X}, "{}")'.format(cp, ''.join(f'\\u{{{ord(ch):X}}}' for ch in s))
        for cp, s in lower
    )
    decimal_rows = ',\n'.join(f'    (0x{cp:04X}, {value})' for cp, value in decimals)
    parts = [
        '// Generated by scripts/pyunicode.py from Python '
        f'{sys.version_info.major}.{sys.version_info.minor} '
        f'(Unicode {unicodedata.unidata_version}). Do not edit.\n',
        '/// The Unicode version these tables come from.\n'
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";\n',
        _rust_ranges(
            'PRINTABLE',
            _ranges(str.isprintable),
            "Code points for which Python's `str.isprintable()` is true.",
        ),
        _rust_ranges(
            'SPACE', _ranges(str.isspace), "Code points for which Python's `str.isspace()` is true."
        ),
        _rust_ranges(
            'CASED', _ranges(_cased), 'Cased code points (lowercase, uppercase or titlecase).'
        ),
        _rust_ranges(
            'CASE_IGNORABLE',
            _ranges(_case_ignorable),
            'Case-ignorable code points, as `str.lower()` treats them.',
        ),
        '/// `str.lower()` of every code point it changes, except the capital sigma\n'
        '/// (context-dependent).\n'
        f'pub const LOWER: &[(u32, &str)] = &[\n{lower_rows},\n];\n',
        "/// The decimal digits Python's `float()` reads, and their values.\n"
        f'pub const DECIMAL: &[(u32, u8)] = &[\n{decimal_rows},\n];\n',
    ]
    return '\n'.join(parts)


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(generate(), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
